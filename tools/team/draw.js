const out = path.join(__dirname, '../../sketches/img/tools');
for (const [name, art] of Object.entries(SPRITES)) {
  const rows = art.trim().split('\n');
  rows.forEach((r, y) => {
    if (r.length !== 24) throw new Error(`${name} row ${y} is ${r.length} wide`);
  });
  if (rows.length !== 24) throw new Error(`${name} is ${rows.length} tall`);
  let rects = '';
  rows.forEach((r, y) => {
    // Runs of one colour in a row become one rect
    for (let x = 0; x < 24; ) {
      const ch = r[x];
      let w = 1;
      while (x + w < 24 && r[x + w] === ch) w++;
      if (ch !== '.') rects += `<rect x="${x}" y="${y}" width="${w}" height="1" fill="${PAL[ch]}"/>`;
      x += w;
    }
  });
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" shape-rendering="crispEdges">${rects}</svg>\n`;
  fs.writeFileSync(path.join(out, `team-${name}.svg`), svg);
}
